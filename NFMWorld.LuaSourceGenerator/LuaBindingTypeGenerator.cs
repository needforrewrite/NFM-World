namespace NFMWorld.LuaSourceGenerator;

internal sealed class LuaBindingTypeGenerator(LuaTypeMetadata type, int baseIndent = 0)
{
    private readonly LuaTypeMetadata _type = type;
    private readonly int _i = baseIndent;

    public string GenerateCode()
    {
        var sb = new CodeBuilder();
        sb.AppendLine("// <auto-generated />");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("#pragma warning disable CS0162");
        sb.AppendLine("#pragma warning disable CS8600");
        sb.AppendLine("#pragma warning disable CS8601");
        sb.AppendLine("#pragma warning disable CS8602");
        sb.AppendLine("#pragma warning disable CS8604");
        sb.AppendLine("#pragma warning disable CS8631");
        sb.AppendLine();
        var ns = _type.Namespace;
        if (!string.IsNullOrEmpty(ns)) sb.AppendLine($"namespace {ns};");
        sb.AppendLine();
        var kw = _type.IsInterface ? "interface" : _type.IsValueType ? "struct" : "class";
        W(sb, _i, $"partial {kw} {_type.TypeName} : Lua.ILuaUserData");
        W(sb, _i, "{");
        var inner = _i + 1;
        Cache(sb, inner);
        Metatable(sb, inner);
        Explicit(sb, inner);
        Operator(sb, inner);
        W(sb, _i, "}");
        sb.AppendLine("#pragma warning restore CS0162");
        sb.AppendLine("#pragma warning restore CS8600");
        sb.AppendLine("#pragma warning restore CS8601");
        sb.AppendLine("#pragma warning restore CS8602");
        sb.AppendLine("#pragma warning restore CS8604");
        sb.AppendLine("#pragma warning restore CS8631");
        return sb.ToString();
    }

    private void Cache(CodeBuilder sb, int i)
    {
        W(sb, i, "private static class __Cache");
        W(sb, i, "{");
        var b = i + 1;
        if (!_type.IsStatic) { Methods(sb, b); Events(sb, b); Index(sb, b); NewIndex(sb, b); }
        W(sb, b, "internal static Lua.LuaTable? __metatable;");
        W(sb, i, "}");
        sb.AppendLine();
    }

    // ---------------------------------------------------------------
    // Methods — only emit for non-inherited; inherited reference impl type
    // ---------------------------------------------------------------
    private void Methods(CodeBuilder sb, int i)
    {
        var seen = new HashSet<string>();
        foreach (var m in _type.InstanceMethods)
        {
            if (!seen.Add(m.LuaName)) continue;
            if (m.IsInherited) continue;

            var ret = m.ReturnType == "void";
            W(sb, i, $"internal static readonly Lua.LuaFunction __function_{m.LuaName} = new(\"{m.LuaName}\", (context, ct) =>");
            W(sb, i, "{");
            var b = i + 1;
            W(sb, b, $"var userData = context.GetArgument<{TypeRef(_type.FullTypeName)}>(0);");
            for (var pi = 0; pi < m.Parameters.Length; pi++)
                W(sb, b, $"var arg{pi} = context.GetArgument<{Ts(m.Parameters[pi])}>({pi + 1});");
            var args = string.Join(", ", Enumerable.Range(0, m.Parameters.Length).Select(pi =>
                m.Parameters[pi].NeedsStructUserData ? $"arg{pi}.Value" : $"arg{pi}"));

            if (m.IsExtension)
            {
                var callArgs = args.Length > 0 ? $"userData, {args}" : "userData";
                if (ret) { W(sb, b, $"{m.DeclaringType}.{m.Name}({callArgs});"); W(sb, b, "return new System.Threading.Tasks.ValueTask<int>(context.Return());"); }
                else { W(sb, b, $"var __result = {m.DeclaringType}.{m.Name}({callArgs});"); W(sb, b, $"return new System.Threading.Tasks.ValueTask<int>(context.Return({WrRet("__result", m)}));"); }
            }
            else
            {
                if (ret) { W(sb, b, $"userData.{m.Name}({args});"); W(sb, b, "return new System.Threading.Tasks.ValueTask<int>(context.Return());"); }
                else { W(sb, b, $"var __result = userData.{m.Name}({args});"); W(sb, b, $"return new System.Threading.Tasks.ValueTask<int>(context.Return({WrRet("__result", m)}));"); }
            }
            W(sb, i, "}");
            W(sb, i, ");");
            sb.AppendLine();
        }
    }

    // ---------------------------------------------------------------
    // Events
    // ---------------------------------------------------------------
    private void Events(CodeBuilder sb, int i)
    {
        foreach (var evt in _type.InstanceEvents)
        {
            W(sb, i, $"internal static readonly Lua.LuaFunction __function_{evt.Name}_add = new(\"add_{evt.LuaName}\", (context, ct) =>");
            W(sb, i, "{");
            W(sb, i + 1, $"var userData = context.GetArgument<{TypeRef(_type.FullTypeName)}>(0);");
            W(sb, i + 1, "return new System.Threading.Tasks.ValueTask<int>(context.Return());");
            W(sb, i, "}"); W(sb, i, ");"); sb.AppendLine();
            W(sb, i, $"internal static readonly Lua.LuaFunction __function_{evt.Name}_remove = new(\"remove_{evt.LuaName}\", (context, ct) =>");
            W(sb, i, "{"); W(sb, i + 1, "return new System.Threading.Tasks.ValueTask<int>(context.Return());");
            W(sb, i, "}"); W(sb, i, ");"); sb.AppendLine();
        }
    }

    // ---------------------------------------------------------------
    // __index — inherited methods reference base/interface impl
    // ---------------------------------------------------------------
    private void Index(CodeBuilder sb, int i)
    {
        W(sb, i, "internal static readonly Lua.LuaFunction __metamethod_index = new(\"index\", (context, ct) =>");
        W(sb, i, "{"); var b = i + 1;
        W(sb, b, $"var userData = context.GetArgument<{TypeRef(_type.FullTypeName)}>(0);");
        W(sb, b, "var key = context.GetArgument(1);");
        W(sb, b, "if (key.TryRead<string>(out var stringKey))");
        W(sb, b, "{"); var body = b + 1;
        foreach (var f in _type.InstanceFields) W(sb, body, $"if (stringKey == \"{f.LuaName}\") return new System.Threading.Tasks.ValueTask<int>(context.Return({WrField("userData." + f.Name, f.FieldType)}));");
        foreach (var p in _type.InstanceProperties.Where(x => x.HasGetter)) W(sb, body, $"if (stringKey == \"{p.LuaName}\") return new System.Threading.Tasks.ValueTask<int>(context.Return({WrField("userData." + p.Name, p.PropertyType)}));");
        foreach (var m in _type.InstanceMethods)
        {
            if (m.IsInherited)
                W(sb, body, $"if (stringKey == \"{m.LuaName}\") return new System.Threading.Tasks.ValueTask<int>(context.Return(new Lua.LuaValue({m.ImplementationSourceType}.__Cache.__function_{m.LuaName})));");
            else
                W(sb, body, $"if (stringKey == \"{m.LuaName}\") return new System.Threading.Tasks.ValueTask<int>(context.Return(new Lua.LuaValue(__Cache.__function_{m.LuaName})));");
        }
        foreach (var evt in _type.InstanceEvents) { W(sb, body, $"if (stringKey == \"add_{evt.LuaName}\") return new System.Threading.Tasks.ValueTask<int>(context.Return(new Lua.LuaValue(__Cache.__function_{evt.Name}_add)));"); W(sb, body, $"if (stringKey == \"remove_{evt.LuaName}\") return new System.Threading.Tasks.ValueTask<int>(context.Return(new Lua.LuaValue(__Cache.__function_{evt.Name}_remove)));"); }
        W(sb, body, "return new System.Threading.Tasks.ValueTask<int>(context.Return(Lua.LuaValue.Nil));");
        W(sb, b, "}");

        if (_type.IsInlineArray && _type.InlineArrayLength.HasValue)
        {
            W(sb, b, "if (key.TryRead<double>(out var num) && double.IsFinite(num) && num >= 1.0 && num <= int.MaxValue)");
            W(sb, b, "{"); W(sb, body, "var index = (int)num - 1;"); W(sb, body, $"if ((uint)index < (uint){_type.InlineArrayLength.Value})");
            W(sb, body, "{");
            var et = _type.InlineArrayElementType ?? "byte";
            W(sb, body + 1, $"ref var element = ref System.Runtime.CompilerServices.Unsafe.Add(ref System.Runtime.CompilerServices.Unsafe.As<{TypeRef(_type.FullTypeName)}, {et}>(ref userData), index);");
            W(sb, body + 1, "return new System.Threading.Tasks.ValueTask<int>(context.Return(Lua.LuaValue.FromObject(element)));");
            W(sb, body, "}"); W(sb, b, "}");
        }
        W(sb, b, "return new System.Threading.Tasks.ValueTask<int>(context.Return(Lua.LuaValue.Nil));");
        W(sb, i, "}"); W(sb, i, ");"); sb.AppendLine();
    }

    // ---------------------------------------------------------------
    // __newindex
    // ---------------------------------------------------------------
    private void NewIndex(CodeBuilder sb, int i)
    {
        W(sb, i, "internal static readonly Lua.LuaFunction __metamethod_newindex = new(\"newindex\", (context, ct) =>");
        W(sb, i, "{"); var b = i + 1;
        W(sb, b, $"var userData = context.GetArgument<{TypeRef(_type.FullTypeName)}>(0);");
        W(sb, b, "var key = context.GetArgument(1);");
        W(sb, b, "if (key.TryRead<string>(out var stringKey))");
        W(sb, b, "{"); var body = b + 1;
        foreach (var f in _type.InstanceFields.Where(x => !x.IsReadOnly)) { W(sb, body, $"if (stringKey == \"{f.LuaName}\")"); W(sb, body, "{"); W(sb, body + 1, $"userData.{f.Name} = context.GetArgument<{TsType(f.FieldType)}>(2);"); W(sb, body + 1, "return new System.Threading.Tasks.ValueTask<int>(context.Return());"); W(sb, body, "}"); }
        foreach (var p in _type.InstanceProperties.Where(x => x.HasSetter)) { W(sb, body, $"if (stringKey == \"{p.LuaName}\")"); W(sb, body, "{"); W(sb, body + 1, $"userData.{p.Name} = context.GetArgument<{TsType(p.PropertyType)}>(2);"); W(sb, body + 1, "return new System.Threading.Tasks.ValueTask<int>(context.Return());"); W(sb, body, "}"); }
        W(sb, body, "throw new Lua.LuaRuntimeException(context.State, $\"'{stringKey}' not found.\");");
        W(sb, b, "}"); W(sb, b, "throw new Lua.LuaRuntimeException(context.State, $\"'{key}' not found.\");");
        W(sb, i, "}"); W(sb, i, ");"); sb.AppendLine();
    }

    // ---------------------------------------------------------------
    // Metatable property
    // ---------------------------------------------------------------
    private void Metatable(CodeBuilder sb, int i)
    {
        W(sb, i, "static Lua.LuaTable? Metatable");
        W(sb, i, "{"); var b = i + 1;
        W(sb, b, "get"); W(sb, b, "{"); var gb = b + 1;
        W(sb, gb, "if (__Cache.__metatable != null) return __Cache.__metatable;"); sb.AppendLine();
        W(sb, gb, "__Cache.__metatable = new();");
        if (!_type.IsStatic)
        {
            W(sb, gb, "__Cache.__metatable[Lua.Runtime.Metamethods.Index] = __Cache.__metamethod_index;");
            W(sb, gb, "__Cache.__metatable[Lua.Runtime.Metamethods.NewIndex] = __Cache.__metamethod_newindex;");
            foreach (var m in _type.InstanceMethods.Where(m => !m.IsInherited))
                W(sb, gb, $"__Cache.__metatable[\"{m.LuaName}\"] = new Lua.LuaValue(__Cache.__function_{m.LuaName});");
            foreach (var evt in _type.InstanceEvents) { W(sb, gb, $"__Cache.__metatable[\"add_{evt.LuaName}\"] = new Lua.LuaValue(__Cache.__function_{evt.Name}_add);"); W(sb, gb, $"__Cache.__metatable[\"remove_{evt.LuaName}\"] = new Lua.LuaValue(__Cache.__function_{evt.Name}_remove);"); }
        }
        W(sb, gb, "return __Cache.__metatable;");
        W(sb, b, "}"); W(sb, b, "set => throw new System.InvalidOperationException(\"The metatable of a [LuaVisible] type cannot be replaced.\");");
        W(sb, i, "}"); sb.AppendLine();
    }

    private void Explicit(CodeBuilder sb, int i)
    {
        W(sb, i, "Lua.LuaTable? Lua.ILuaUserData.Metatable");
        W(sb, i, "{"); W(sb, i + 1, "get => Metatable;"); W(sb, i + 1, "set => Metatable = value;");
        W(sb, i, "}"); sb.AppendLine();
    }

    private void Operator(CodeBuilder sb, int i)
    {
        if (_type.IsInterface) return; // Cannot declare user-defined conversions on interfaces (CS0552)
        W(sb, i, $"public static implicit operator Lua.LuaValue({_type.TypeName} value)");
        W(sb, i, "{"); W(sb, i + 1, "return Lua.LuaValue.FromUserData(value);"); W(sb, i, "}");
    }

    // ------------------------------------------------------------------
    // Type helpers
    // ------------------------------------------------------------------
    private static void W(CodeBuilder sb, int i, string line) => sb.AppendLineIndented(line, i);

    /// <summary>Type reference for GetArgument — uses StructUserData if type is external.</summary>
    private static string TypeRef(string t) => t;

    /// <summary>Stack type for parameter — wraps in StructUserData if needed.</summary>
    private static string Ts(LuaParameterMetadata p) =>
        p.NeedsStructUserData ? $"nfm_world_library.Lua.StructUserData<{p.Type}>" : TsType(p.Type);

    /// <summary>Stack type for a raw type string.</summary>
    private static string TsType(string t) => t switch
    {
        "int" => "int", "long" => "long", "float" => "float", "double" => "double",
        "bool" => "bool", "string" => "string", "object" => "object", "void" => "void",
        "byte" => "byte", "sbyte" => "sbyte", "short" => "short", "ushort" => "ushort",
        "uint" => "uint", "ulong" => "ulong", "decimal" => "decimal",
        "int?" => "int?", "long?" => "long?", "float?" => "float?", "double?" => "double?",
        "bool?" => "bool?", _ => t
    };

    /// <summary>Wrap return value for a method.</summary>
    private static string WrRet(string expr, LuaMethodMetadata m)
    {
        if (m.ReturnType == "void") return expr;
        if (IsSimple(m.ReturnType)) return $"({expr})";
        if (NeedsStructWrap(m.ReturnType))
        {
            var mtRef = GetMetatableRef(m.ReturnType);
            return $"Lua.LuaValue.FromUserData(new nfm_world_library.Lua.StructUserData<{m.ReturnType}>({mtRef}) {{ Value = {expr} }})";
        }
        return $"Lua.LuaValue.FromUserData({expr})";
    }

    /// <summary>Wrap field/property return value.</summary>
    private static string WrField(string expr, string rt)
    {
        if (rt == "void") return expr;
        if (IsSimple(rt)) return $"({expr})";
        if (NeedsStructWrap(rt))
        {
            var mtRef = GetMetatableRef(rt);
            return $"Lua.LuaValue.FromUserData(new nfm_world_library.Lua.StructUserData<{rt}>({mtRef}) {{ Value = {expr} }})";
        }
        return $"Lua.LuaValue.FromUserData({expr})";
    }

    private static string GetMetatableRef(string typeName)
    {
        // Complex types (tuples, constructed generics, arrays of generics) — no metatable available
        if (typeName.Contains('(') || typeName.Contains(')'))
            return "null";
        // Try to match a generated metatable by sanitized name
        var safe = Sanitize(typeName);
        // For types that likely have a generated metatable (simple named types), reference it
        // For everything else, use a shared fallback or null
        return $"StructUserData_Metatable_{safe}.Metatable";
    }

    private static bool IsSimple(string t) => t switch
    {
        "int" or "long" or "float" or "double" or "bool" or "string" or "object"
            or "byte" or "sbyte" or "short" or "ushort" or "uint" or "ulong" or "decimal" or "char" => true,
        _ => t.Contains("Fixed64") || t.Contains("Vector3d") || t.Contains("f64AngleSingle") || t.Contains("f64Euler")
    };

    private static bool NeedsStructWrap(string t)
    {
        if (IsSimple(t)) return false;
        // Complex types (tuples, etc.) can't be code-generated cleanly
        if (t.Contains('(') || t.Contains(')')) return false;
        return true;
    }

    private static string Sanitize(string name) =>
        name.Replace("global::", "").Replace("<", "_").Replace(">", "_")
            .Replace("?", "_Nullable").Replace("[]", "Array").Replace(",", "_")
            .Replace(" ", "").Replace("*", "Ptr").Replace(".", "_");
}
