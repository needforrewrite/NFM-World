using System.Collections.Generic;
using System.Linq;

namespace TightPack.Generator;

internal static class Emitter
{
    private const string WriterType = "global::TightPack.TightPackWriter<TBufferWriter>";

    public static string Emit(TypeModel model)
    {
        var w = new CodeWriter();

        w.Line("// <auto-generated/>");
        w.Line("#nullable disable");
        w
            .Line(
                "#pragma warning disable CS0162, CS0164, CS0168, CS0169, CS0219, CS0414, CS0618, CS8600, CS8601, CS8602, CS8603, CS8604, CS8618, CS8625, CS8765"
            );
        w.Blank();

        if (model.Namespace.Length != 0)
        {
            w.Open($"namespace {model.Namespace}");
        }

        foreach (string container in model.Containers)
        {
            w.Open(container);
        }

        w.Open($"{model.Declaration} : global::TightPack.ITightPackable<{model.TypeName}>");

        if (model.Blittable)
        {
            // Runs on the first static access to the type, which Serialize itself guarantees, so a
            // layout the analyzer got wrong fails loudly instead of writing padding bytes.
            w.Line(
                "private static readonly bool __tightPackLayout = " +
                $"global::TightPack.TightPackBlit.VerifySize<{model.TypeName}>({model.BlittableSize});"
            );
            w.Blank();
        }

        EmitRegistrations(w, model);

        if (model.Blittable)
        {
            EmitBlittable(w, model);
        }
        else if (model.Kind == GenerateKind.Union)
        {
            EmitUnion(w, model);
        }
        else if (model.Kind == GenerateKind.Collection)
        {
            EmitCollection(w, model);
        }
        else
        {
            EmitObject(w, model);
        }

        w.Close();

        for (int i = 0; i < model.Containers.Count; i++)
        {
            w.Close();
        }

        if (model.Namespace.Length != 0)
        {
            w.Close();
        }

        return w.ToString();
    }

    /// <summary>
    /// Emits a static field per member formatter and registers them from the static constructor.
    /// The field keeps the hot path to a direct call, and naming the formatter here is also what
    /// keeps the instantiation reachable for the AOT compiler; the registration makes it visible to
    /// types that resolve formatters at runtime.
    /// </summary>
    private static void EmitRegistrations(CodeWriter w, TypeModel model)
    {
        var registrations = new List<string>
        {
            $"new global::TightPack.TightPackableFormatter<{model.TypeName}>()",
        };

        var fields = new List<(string Field, string MemberType, string Expression)>();
        for (int i = 0; i < model.Members.Count; i++)
        {
            MemberModel member = model.Members[i];
            if (member.FormatterExpression is null)
            {
                continue;
            }

            string field = $"__f{i}";
            member.FormatterField = field;
            fields.Add((field, member.TypeName, member.FormatterExpression));
            registrations.Add(field);
        }

        var caseRegistrations = new List<string>();
        foreach (UnionCaseModel unionCase in model.UnionCases)
        {
            caseRegistrations.Add($"new global::TightPack.TightPackableFormatter<{unionCase.TypeName}>()");
        }

        foreach ((string field, string memberType, string expression) in fields)
        {
            w.Line(
                $"private static readonly global::TightPack.TightPackFormatter<{memberType}> {field} = {expression};"
            );
        }

        if (fields.Count != 0)
        {
            w.Blank();
        }

        w.Open($"static {model.SimpleName}()");
        foreach (string registration in registrations)
        {
            w.Line($"global::TightPack.TightPackFormatterProvider.Register({registration});");
        }

        foreach (string registration in model.DependentFormatters)
        {
            w.Line(registration);
        }

        w.Close();
        w.Blank();
    }

    private static void BeginSerialize(CodeWriter w, TypeModel model)
    {
        w.Open(
            $"static void global::TightPack.ITightPackable<{model.TypeName}>.Serialize<TBufferWriter>(" +
            $"ref {WriterType} writer, in {model.TypeName} value)"
        );
    }

    private static void BeginDeserialize(CodeWriter w, TypeModel model) =>
        w.Open(
            $"static void global::TightPack.ITightPackable<{model.TypeName}>.Deserialize(" +
            "ref global::TightPack.TightPackReader reader, ref " + model.TypeName + " value)"
        );

    // ----- blittable -----

    private static void EmitBlittable(CodeWriter w, TypeModel model)
    {
        BeginSerialize(w, model);
        w.Line($"writer.WriteObjectHeader({model.Members.Count});");
        w.Line($"writer.WriteBlittable(in value, {model.BlittableSize});");
        w.Close();
        w.Blank();

        BeginDeserialize(w, model);
        w.Open("if (!reader.TryReadObjectHeader(out byte __header))");
        w.Line("value = default;");
        w.Line("return;");
        w.Close();
        w.Blank();
        w.Open($"if (__header != {model.Members.Count})");
        w.Line(
            "global::TightPack.TightPackSerializationException.ThrowInvalidMemberCount(" +
            $"typeof({model.TypeName}), {model.Members.Count}, __header);"
        );
        w.Close();
        w.Blank();
        w.Line($"value = reader.ReadBlittable<{model.TypeName}>({model.BlittableSize});");
        w.Close();
    }

    // ----- object / version tolerant / circular -----

    private static void EmitObject(CodeWriter w, TypeModel model)
    {
        bool tolerant = model.Kind is GenerateKind.VersionTolerant or GenerateKind.CircularReference;
        bool circular = model.Kind == GenerateKind.CircularReference;
        string count = model.Members.Count.ToString();

        BeginSerialize(w, model);

        if (!model.IsValueType)
        {
            w.Open("if (value is null)");
            w.Line("writer.WriteNullObjectHeader();");
            w.Line("return;");
            w.Close();
            w.Blank();
        }

        if (circular)
        {
            w.Open($"if (!writer.WriteObjectReference({count}, value))");
            w.Line("return;");
            w.Close();
        }
        else
        {
            w.Line($"writer.WriteObjectHeader({count});");
        }

        EmitCallbacks(w, model.OnSerializing, "value");

        if (tolerant && model.Members.Count != 0)
        {
            w.Line("var __scratch = global::TightPack.TightPackScratch.Rent();");
            w.Open("try");
            // Share the outer state so a circular reference inside this member still resolves.
            w.Line(
                "var __sw = new global::TightPack.TightPackWriter<global::TightPack.TightPackBufferWriter>(" +
                "ref __scratch, writer.State, writer.Depth);"
            );
            foreach (MemberModel member in model.Members)
            {
                w.Line($"var __w_{member.Name} = value.{member.Name};");
                EmitValueWrite(w, "__sw", $"__w_{member.Name}", member);
                w.Line("__sw.Flush();");
                w.Line("global::TightPack.TightPackScratch.Commit(ref writer, __scratch);");
            }

            w.Close();
            w.Open("finally");
            w.Line("global::TightPack.TightPackScratch.Return(__scratch);");
            w.Close();
        }
        else
        {
            foreach (MemberModel member in model.Members)
            {
                w.Line($"var __w_{member.Name} = value.{member.Name};");
                EmitValueWrite(w, "writer", $"__w_{member.Name}", member);
            }
        }

        EmitCallbacks(w, model.OnSerialized, "value");
        w.Close();
        w.Blank();

        EmitObjectDeserialize(w, model, tolerant, circular);
    }

    private static void EmitObjectDeserialize(CodeWriter w, TypeModel model, bool tolerant, bool circular)
    {
        BeginDeserialize(w, model);

        if (circular)
        {
            // The instance exists before its members are read, so a cycle can resolve to it.
            w.Open(
                "if (!reader.TryReadObjectReferenceHeader(" +
                "out byte __header, out object __existing, out bool __isReference))"
            );
            w.Line("value = default;");
            w.Line("return;");
            w.Close();
            w.Blank();
            w.Open("if (__isReference)");
            w.Line($"value = ({model.TypeName})__existing;");
            w.Line("return;");
            w.Close();
            w.Blank();
            w.Line($"value = new {model.TypeName}();");
            w.Line("reader.State.AddObject(value);");
            EmitCallbacks(w, model.OnDeserializing, "value");
        }
        else
        {
            w.Open("if (!reader.TryReadObjectHeader(out byte __header))");
            w.Line("value = default;");
            w.Line("return;");
            w.Close();
            w.Blank();

            if (!tolerant)
            {
                w.Open($"if (__header != {model.Members.Count})");
                w.Line(
                    "global::TightPack.TightPackSerializationException.ThrowInvalidMemberCount(" +
                    $"typeof({model.TypeName}), {model.Members.Count}, __header);"
                );
                w.Close();
                w.Blank();
            }

            // The in-place path rebuilds a fresh instance so callbacks and member writes observe the
            // real object rather than a caller's previous value.
            bool inPlaceHere = UsesInPlace(model);
            if (inPlaceHere)
            {
                w.Line($"value = new {model.TypeName}();");
                EmitCallbacks(w, model.OnDeserializing, "value");
            }
        }

        if (tolerant)
        {
            EmitTolerantRead(w, model, circular || UsesInPlace(model));
        }
        else
        {
            EmitLocalsAndReads(w, model, circular || UsesInPlace(model));
        }

        EmitCallbacks(w, model.OnDeserialized, "value");
        w.Close();
    }

    /// <summary>
    /// True when the value can be filled in after construction. A type with an init-only, getter-only
    /// or <c>required</c> member has to be built through an object initializer instead: a required
    /// member cannot be left unset by a plain <c>new</c>.
    /// </summary>
    private static bool UsesInPlace(TypeModel model) =>
        !model.IsValueType
        && model.Ctor is null
        && model.Members.TrueForAll(m => m.CanAssignDirect && !m.IsRequired);

    private static void EmitLocalsAndReads(CodeWriter w, TypeModel model, bool inPlace)
    {
        for (int i = 0; i < model.Members.Count; i++)
        {
            w.Line($"{model.Members[i].TypeName} __m{i} = default;");
        }

        w.Blank();

        for (int i = 0; i < model.Members.Count; i++)
        {
            EmitValueRead(w, $"__m{i}", model.Members[i]);
        }

        w.Blank();

        if (inPlace)
        {
            for (int i = 0; i < model.Members.Count; i++)
            {
                w.Line($"value.{model.Members[i].Name} = __m{i};");
            }
        }
        else
        {
            EmitAssign(w, model);
        }
    }

    private static void EmitTolerantRead(CodeWriter w, TypeModel model, bool inPlace)
    {
        for (int i = 0; i < model.Members.Count; i++)
        {
            w.Line($"{model.Members[i].TypeName} __m{i} = default;");
        }

        w.Blank();

        // Each member carries its own length, so a member this build does not know is skipped
        // instead of desynchronising everything after it.
        w.Open("for (int __i = 0; __i < __header; __i++)");
        w.Line("int __length = (int)reader.ReadVarUInt32();");
        w.Open("if (__length == 0)");
        w.Line("continue;");
        w.Close();
        w.Line("int __start = reader.Consumed;");
        w.Blank();
        w.Open("switch (__i)");

        for (int i = 0; i < model.Members.Count; i++)
        {
            w.Open($"case {i}:");
            EmitValueRead(w, $"__m{i}", model.Members[i]);
            w.Line("break;");
            w.Close();
        }

        w.Close();
        w.Blank();
        w.Line("int __used = reader.Consumed - __start;");
        w.Open("if (__used > __length)");
        w.Line("global::TightPack.TightPackSerializationException.ThrowOverrun(__length, __used, reader.Remaining);");
        w.Close();
        w.Line("reader.Skip(__length - __used);");
        w.Close();
        w.Blank();

        if (inPlace)
        {
            for (int i = 0; i < model.Members.Count; i++)
            {
                w.Line($"value.{model.Members[i].Name} = __m{i};");
            }
        }
        else
        {
            EmitAssign(w, model);
        }
    }

    private static void EmitAssign(CodeWriter w, TypeModel model)
    {
        if (model.Ctor is null)
        {
            var initializers = new List<string>();
            for (int i = 0; i < model.Members.Count; i++)
            {
                initializers.Add($"{model.Members[i].Name} = __m{i}");
            }

            if (initializers.Count == 0)
            {
                w.Line($"value = new {model.TypeName}();");
                return;
            }

            w.Line($"value = new {model.TypeName} {{ {string.Join(", ", initializers)} }};");
            return;
        }

        var arguments = new List<string>();
        var bound = new HashSet<int>();
        foreach (int index in model.Ctor.ParameterMembers)
        {
            arguments.Add(index >= 0 ? $"__m{index}" : "default");
            if (index >= 0)
            {
                bound.Add(index);
            }
        }

        var extra = new List<string>();
        for (int i = 0; i < model.Members.Count; i++)
        {
            if (!bound.Contains(i) && model.Members[i].CanAssign)
            {
                extra.Add($"{model.Members[i].Name} = __m{i}");
            }
        }

        string construction = $"new {model.TypeName}({string.Join(", ", arguments)})";
        if (extra.Count != 0)
        {
            construction += " { " + string.Join(", ", extra) + " }";
        }

        w.Line($"value = {construction};");
    }

    // ----- union -----

    private static void EmitUnion(CodeWriter w, TypeModel model)
    {
        BeginSerialize(w, model);
        w.Open("if (value is null)");
        w.Line("writer.WriteNullUnionHeader();");
        w.Line("return;");
        w.Close();
        w.Blank();

        foreach (UnionCaseModel unionCase in model.UnionCases)
        {
            w.Open($"if (value is {unionCase.TypeName} __case{unionCase.Tag})");
            w.Line($"writer.WriteUnionHeader({unionCase.Tag});");
            w.Line($"writer.WritePackable(in __case{unionCase.Tag});");
            w.Line("return;");
            w.Close();
        }

        w.Line(
            "global::TightPack.TightPackSerializationException.ThrowUnionValueNotMapped(" +
            $"value.GetType(), typeof({model.TypeName}));"
        );
        w.Close();
        w.Blank();

        BeginDeserialize(w, model);
        w.Open("if (!reader.TryReadUnionHeader(out ushort __tag))");
        w.Line("value = default;");
        w.Line("return;");
        w.Close();
        w.Blank();
        w.Open("switch (__tag)");

        foreach (UnionCaseModel unionCase in model.UnionCases)
        {
            w.Open($"case {unionCase.Tag}:");
            w.Line($"{unionCase.TypeName} __case = default;");
            w.Line("reader.ReadPackable(ref __case);");
            w.Line($"value = __case;");
            w.Line("return;");
            w.Close();
        }

        w.Close();
        w.Blank();
        w.Line(
            "global::TightPack.TightPackSerializationException.ThrowInvalidUnionTag(" +
            $"__tag, typeof({model.TypeName}));"
        );
        w.Close();
    }

    // ----- collection -----

    private static void EmitCollection(CodeWriter w, TypeModel model)
    {
        MemberModel element = model.Members[0];
        string elementType = element.TypeName;

        BeginSerialize(w, model);
        w.Open("if (value is null)");
        w.Line("writer.WriteNullCollectionHeader();");
        w.Line("return;");
        w.Close();
        w.Blank();
        w.Line($"global::System.Collections.Generic.ICollection<{elementType}> __items = value;");
        w.Line("writer.WriteCollectionHeader(__items.Count);");
        w.Open($"foreach ({elementType} __item in __items)");
        EmitValueWrite(w, "writer", "__item", element);
        w.Close();
        w.Close();
        w.Blank();

        BeginDeserialize(w, model);
        w.Open("if (!reader.TryReadCollectionHeader(out int __count))");
        w.Line("value = default;");
        w.Line("return;");
        w.Close();
        w.Line($"var __result = new {model.TypeName}();");
        w.Open("for (int __i = 0; __i < __count; __i++)");
        w.Line($"{elementType} __item = default;");
        EmitValueRead(w, "__item", element);
        w.Line("__result.Add(__item);");
        w.Close();
        w.Line("value = __result;");
        w.Close();
    }

    // ----- member read/write -----

    private static void EmitValueWrite(CodeWriter w, string writerExpr, string valueExpr, MemberModel member)
    {
        switch (member.WriteKind)
        {
            case MemberWriteKind.Scalar:
                w.Line($"{writerExpr}.Write{member.Method}({valueExpr});");
                break;
            case MemberWriteKind.Enum:
                w.Line($"{writerExpr}.WriteEnum({valueExpr});");
                break;
            case MemberWriteKind.String:
                w.Line($"{writerExpr}.WriteString({valueExpr});");
                break;
            case MemberWriteKind.Packable:
                w.Line($"{writerExpr}.WritePackable(in {valueExpr});");
                break;
            case MemberWriteKind.Formatter when member.FormatterField is not null:
                w.Line($"{writerExpr}.WriteValueWithFormatter({member.FormatterField}, in {valueExpr});");
                break;
            case MemberWriteKind.Tuple:
                for (int i = 0; i < member.TupleElements!.Count; i++)
                {
                    MemberModel element = member.TupleElements[i];
                    EmitValueWrite(w, writerExpr, $"{valueExpr}.Item{i + 1}", element);
                }

                break;
            default:
                w.Line($"{writerExpr}.WriteValue(in {valueExpr});");
                break;
        }
    }

    private static void EmitValueRead(CodeWriter w, string target, MemberModel member)
    {
        switch (member.WriteKind)
        {
            case MemberWriteKind.Scalar:
                w.Line($"{target} = reader.Read{member.Method}();");
                break;
            case MemberWriteKind.Enum:
                w.Line($"{target} = reader.ReadEnum<{member.TypeName}>();");
                break;
            case MemberWriteKind.String:
                w.Line($"{target} = reader.ReadString();");
                break;
            case MemberWriteKind.Packable:
                w.Line($"reader.ReadPackable(ref {target});");
                break;
            case MemberWriteKind.Formatter when member.FormatterField is not null:
                w.Line($"reader.ReadValueWithFormatter({member.FormatterField}, ref {target});");
                break;
            case MemberWriteKind.Tuple:
                string tupleLocal = $"{target.Replace(".", "_")}_tuple";
                for (int i = 0; i < member.TupleElements!.Count; i++)
                {
                    MemberModel element = member.TupleElements[i];
                    w.Line($"{element.TypeName} {tupleLocal}{i} = default;");
                    EmitValueRead(w, $"{tupleLocal}{i}", element);
                }

                w.Line($"{target} = ({member.TypeName})(" +
                       string.Join(", ", Enumerable.Range(0, member.TupleElements.Count).Select(i => $"{tupleLocal}{i}")) +
                       ");");
                break;
            default:
                w.Line($"reader.ReadValue(ref {target});");
                break;
        }
    }

    private static void EmitCallbacks(CodeWriter w, List<string> methods, string receiver)
    {
        foreach (string method in methods)
        {
            w.Line($"{receiver}.{method}();");
        }
    }
}
